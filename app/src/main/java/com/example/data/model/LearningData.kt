package com.example.data.model

data class AlphabetItem(
    val id: Int,
    val letter: String,
    val name: String,
    val exampleWord: String,
    val emoji: String,
    val sentence: String,
    val isCompleted: Boolean = false
)

data class NumberItem(
    val number: Int,
    val arabicDigit: String,
    val arabicName: String,
    val emoji: String,
    val itemsCount: Int
)

data class MathQuestion(
    val id: Int,
    val num1: Int,
    val num2: Int,
    val operation: String, // "+" or "-"
    val options: List<Int>,
    val correctAnswer: Int,
    val emojiTopic: String
)

data class VocabularyCard(
    val id: Int,
    val category: String, // الحيوانات، الألوان، الفواكه، النقل
    val wordArabic: String,
    val emoji: String,
    val pronunciationNote: String
)

data class RhymeItem(
    val id: Int,
    val title: String,
    val iconEmoji: String,
    val category: String,
    val lyrics: String
)

